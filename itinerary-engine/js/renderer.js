  /* =====================================================
     BASIC HELPERS
  ===================================================== */

  function safeArray(value) {

    return Array.isArray(value)
      ? value
      : [];

  }


  function getImagesFromKeys(keys = []) {

    if (
      typeof window.getImages !== "function"
    ) {
      return [];
    }

    return window.getImages(keys);

  }


  function firstImage(key) {

    const images =
      getImagesFromKeys([key]);

    return images.length
      ? images[0]
      : "";

  }


