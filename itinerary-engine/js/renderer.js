  /* =====================================================
     MEAL BADGE CLASS
  ===================================================== */

  function mealClass(value = "") {

    const text =
      String(value).toLowerCase();


    if (
      text.includes("included") &&
      !text.includes("not included") &&
      !text.includes("not confirmed")
    ) {
      return "yes";
    }


    if (
      text.includes("mentioned") ||
      text.includes("not confirmed") ||
      text.includes("direct payment")
    ) {
      return "meal-note";
    }


    return "na";

  }


  /* =====================================================
     IMAGE CAROUSEL
  ===================================================== */

  function carousel(images, id) {

    if (!images.length) {

      return `
        <div class="imgbox">

          <div style="
            width:100%;
            height:100%;
            min-height:470px;
            display:flex;
            align-items:center;
            justify-content:center;
            color:#CBD5E1;
            font-weight:800;
            text-align:center;
            padding:30px;
          ">
            Image unavailable
          </div>

        </div>
      `;

    }


    const slides =
      images
        .map((src, index) => `

          <div class="slideimg">

            <img
              src="${src}"
              alt=""
              loading="eager"
              onerror="removeBrokenImage(this, '${id}')"
            >

          </div>

        `)
        .join("");


    return `
      <div class="imgbox">

        <div
          class="track"
          id="${id}"
          data-index="0"
        >
          ${slides}
        </div>


        ${
          images.length > 1
            ? `

              <button
                class="btn prev"
                onclick="moveSlide('${id}', -1)"
                aria-label="Previous image"
              >
                ❮
              </button>


              <button
                class="btn next"
                onclick="moveSlide('${id}', 1)"
                aria-label="Next image"
              >
                ❯
              </button>

            `
            : ""
        }

      </div>
    `;

  }


