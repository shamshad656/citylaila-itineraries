/* =========================================================
   GLOBAL CAROUSEL CONTROLS
========================================================= */

window.moveSlide =
function (id, direction) {

  const track =
    document.getElementById(id);


  if (!track) {
    return;
  }


  const slides =
    track.querySelectorAll(".slideimg");


  if (slides.length <= 1) {
    return;
  }


  let index =
    parseInt(
      track.dataset.index || "0",
      10
    );


  index +=
    direction;


  if (index < 0) {

    index =
      slides.length - 1;

  }


  if (index >= slides.length) {

    index =
      0;

  }


  track.dataset.index =
    String(index);


  track.style.transform =
    `translateX(-${index * (100 / slides.length)}%)`;

};


/* =========================================================
   BROKEN IMAGE PROTECTION

   If any external image URL fails:
   - remove broken slide
   - resize remaining slides
   - reset carousel
========================================================= */

window.removeBrokenImage =
function (img, trackId) {

  const slide =
    img.closest(".slideimg");


  if (slide) {
    slide.remove();
  }


  const track =
    document.getElementById(trackId);


  if (!track) {
    return;
  }


  const slides =
    track.querySelectorAll(".slideimg");


  const count =
    slides.length;


  /* =====================================================
     NO IMAGE LEFT
  ===================================================== */

  if (!count) {

    track.style.width =
      "100%";


    track.innerHTML = `

      <div style="
        width:100%;
        height:100%;
        min-height:470px;

        display:flex;

        justify-content:center;
        align-items:center;

        color:#CBD5E1;

        font-weight:800;

        text-align:center;

        padding:30px;
      ">

        Image unavailable

      </div>

    `;


    const container =
      track.closest(".imgbox");


    if (container) {

      container
        .querySelectorAll(".btn")
        .forEach(button => {

          button.style.display =
            "none";

        });

    }


    return;

  }


  /* =====================================================
     RECALCULATE CAROUSEL
  ===================================================== */

  track.style.width =
    `${count * 100}%`;


  slides.forEach(slide => {

    slide.style.width =
      `${100 / count}%`;

    slide.style.minWidth =
      `${100 / count}%`;

  });


  track.dataset.index =
    "0";


  track.style.transform =
    "translateX(0)";


  /* =====================================================
     HIDE CONTROLS IF ONLY ONE IMAGE
  ===================================================== */

  const container =
    track.closest(".imgbox");


  if (
    container &&
    count <= 1
  ) {

    container
      .querySelectorAll(".btn")
      .forEach(button => {

        button.style.display =
          "none";

      });

  }

};