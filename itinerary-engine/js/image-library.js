/* =========================================================
   IMAGE HELPER

   Example:

   getImages([
     "burj_al_arab",
     "palm_jumeirah",
     "atlantis_the_palm"
   ]);

   It automatically combines all image URLs.
========================================================= */

window.getImages = function (keys = []) {

  const finalImages = [];

  keys.forEach(key => {

    const images = window.IMAGE_LIBRARY[key];

    if (Array.isArray(images)) {
      finalImages.push(...images);
    }

  });

  return finalImages;
};


